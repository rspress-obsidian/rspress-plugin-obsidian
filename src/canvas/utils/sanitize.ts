import DOMPurify from 'isomorphic-dompurify';

export function sanitizeHtml(html: string): string {
  return DOMPurify.sanitize(html, {
    ALLOWED_TAGS: [
      'p',
      'div',
      'span',
      'h1',
      'h2',
      'h3',
      'h4',
      'h5',
      'h6',
      'br',
      'hr',
      'strong',
      'b',
      'em',
      'i',
      'code',
      'pre',
      'blockquote',
      'ul',
      'ol',
      'li',
      'a',
      'img',
      'table',
      'thead',
      'tbody',
      'tr',
      'th',
      'td',
      'del',
      's',
      'sub',
      'sup',
      'video',
      'audio',
      'source',
      'iframe',
      'track',
      'figure',
      'figcaption',
    ],
    ALLOWED_ATTR: [
      'href',
      'src',
      'alt',
      'title',
      'class',
      'target',
      'rel',
      'width',
      'height',
      'controls',
      'sandbox',
      'allow',
      'type',
      'media',
      'poster',
      'preload',
      'loop',
      'muted',
      'kind',
      'label',
    ],
  });
}
